"""Reproduce adaptive algorithms from the frozen Crawl4AI source."""
import ast
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / 'upstream/crawl4ai/crawl4ai-838869bdda93f25e6d50b3f50ae9577d9b19a586/crawl4ai/adaptive_crawler.py'
TARGET = Path(__file__).with_name('adaptive_algorithms.py')

def embedding_source(tree):
    selected=next(node for node in tree.body if isinstance(node,ast.ClassDef) and node.name=='EmbeddingStrategy')
    methods={'__init__','_compute_distance_matrix','_get_cached_distance_matrix','compute_coverage_shape',
        '_sample_boundary_points','find_coverage_gaps','select_links_for_expansion','calculate_confidence',
        'rank_links','validate_coverage','should_stop','update_state'}
    selected.bases=[];selected.body=[n for n in selected.body if isinstance(n,(ast.FunctionDef,ast.AsyncFunctionDef)) and n.name in methods]
    class InjectLocal(ast.NodeTransformer):
        def visit_ImportFrom(self,node):return None if node.module=='utils' else node
        def visit_Assign(self,node):
            if any(isinstance(t,ast.Name) and t.id=='embedding_llm_config' for t in node.targets):return None
            return self.generic_visit(node)
        def visit_Call(self,node):
            if isinstance(node.func,ast.Name) and node.func.id=='get_text_embeddings':
                return ast.Call(func=ast.Attribute(value=ast.Name(id='self',ctx=ast.Load()),attr='_get_embeddings',ctx=ast.Load()),args=[node.args[0]],keywords=[])
            return self.generic_visit(node)
    selected=InjectLocal().visit(selected);ast.fix_missing_locations(selected)
    header='''# Source-derived Crawl4AI EmbeddingStrategy, commit838869bdda93f25e6d50b3f50ae9577d9b19a586.
# Apache-2.0 and attribution retained; see adaptive-source-manifest.json.
# Changes: injected local embedding acquisition; no global remote provider imports.
from __future__ import annotations
import numpy as np

def cosine_similarity(a,b):
    return float(np.dot(a,b)/(np.linalg.norm(a)*np.linalg.norm(b)))

def cosine_distance(a,b):
    return 1-cosine_similarity(a,b)

'''
    target=TARGET.with_name('adaptive_embedding_algorithms.py')
    target.write_text(header+ast.unparse(selected)+'\n',encoding='utf-8')
    return {'path':target.name,'sha256':hashlib.sha256(target.read_bytes()).hexdigest(),'methods':sorted(methods)}

def main():
    original = SOURCE.read_text(encoding='utf-8')
    tree = ast.parse(original)
    selected = [node for node in tree.body if isinstance(node, ast.ClassDef) and node.name in {'CrawlStrategy', 'StatisticalStrategy'}]
    source = '\n\n'.join(ast.get_source_segment(original, node) for node in selected)
    # Upstream compares the term string to document-id integers. Membership must
    # use the document id (currently equivalent for one update per document).
    source = source.replace('if term not in state.documents_with_terms[term]:', 'if doc_id not in state.documents_with_terms[term]:')
    header = '''"""Source-derived Crawl4AI adaptive statistical strategy.
Copyright upstream authors; Apache-2.0 and required attribution in LICENSE.crawl4ai/NOTICE.
Generated by adaptive_migration.py; shared product owns network, state and lifecycle.
"""
from __future__ import annotations
from abc import ABC, abstractmethod
import math
import re
'''
    TARGET.write_text(header + '\n' + source + '\n', encoding='utf-8')
    manifest = {'upstream_commit':'838869bdda93f25e6d50b3f50ae9577d9b19a586',
                'source':str(SOURCE.relative_to(ROOT)).replace('\\','/'),
                'source_sha256':hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
                'symbols':[n.name for n in selected],
                'target':TARGET.name,'target_sha256':hashlib.sha256(TARGET.read_bytes()).hexdigest(),
                'changes':['Future annotations decouple original model/config dependencies.',
                           'Correct document-frequency membership to compare document id with ids.',
                           'Original network-owning AdaptiveCrawler, JSON file persistence and remote embedding/query providers are not imported.']}
    driver=TARGET.with_name('adaptive.py')
    if driver.exists():manifest['driver']={'path':driver.name,'sha256':hashlib.sha256(driver.read_bytes()).hexdigest()}
    manifest['embedding_algorithms']=embedding_source(tree)
    driver=TARGET.with_name('adaptive_embedding.py')
    manifest['embedding_driver']={'path':driver.name,'sha256':hashlib.sha256(driver.read_bytes()).hexdigest()}
    manifest['changes']+=['EmbeddingStrategy math/shape/ranking/validation/convergence reused with injected local CPU vectors.',
        'Remote query generation replaced by explicit bounded shared local model generation and deterministic held-out split.',
        'Original centroid/radius shape and empty boundary sampler retained; no real alpha-shape implementation claimed.']
    TARGET.with_name('adaptive-source-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({'generated':TARGET.name,'sha256':manifest['target_sha256']}))

if __name__=='__main__':main()
